#!/usr/bin/env node
/**
 * Regenerates channels/shopify-taxonomy.generated.ts from a released version
 * of Shopify's Standard Product Taxonomy (https://github.com/Shopify/product-taxonomy).
 *
 * Usage (from services/export):
 *   node scripts/update-shopify-taxonomy.mjs v2026-11
 *
 * Shopify accepts a category in the product CSV as its full breadcrumb or its
 * id; the export writes the breadcrumb and checks it against this list.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const version = process.argv[2];
if (!/^v\d{4}-\d{2}$/.test(version ?? '')) {
  console.error('Usage: node scripts/update-shopify-taxonomy.mjs v2026-11');
  process.exit(1);
}
const url = `https://raw.githubusercontent.com/Shopify/product-taxonomy/${version}/dist/en/categories.txt`;
const res = await fetch(url);
if (!res.ok) {
  console.error(`Download failed (${res.status}): ${url}`);
  process.exit(1);
}
const text = await res.text();
const rows = [];
for (const line of text.split(/\r?\n/)) {
  const m = /^gid:\/\/shopify\/TaxonomyCategory\/(\S+)\s+:\s+(.+?)\s*$/.exec(line);
  if (m) rows.push(`${m[1]}\t${m[2]}`);
}
if (rows.length < 1000) {
  console.error(`Only ${rows.length} categories parsed; refusing to write.`);
  process.exit(1);
}
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'channels', 'shopify-taxonomy.generated.ts');
const body = [
  '/* eslint-disable */',
  `// GENERATED by scripts/update-shopify-taxonomy.mjs from Shopify product-taxonomy ${version}. Do not edit.`,
  `export const SHOPIFY_TAXONOMY_VERSION = ${JSON.stringify(version)};`,
  '/** One category per line: "<id>\\t<full breadcrumb>". */',
  `export const SHOPIFY_TAXONOMY_TSV = ${JSON.stringify(rows.join('\n'))};`,
  '',
].join('\n');
writeFileSync(out, body);
console.log(`Wrote ${rows.length} categories (${version}) to ${path.relative(process.cwd(), out)}`);
